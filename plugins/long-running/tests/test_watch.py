def run_watch(name: str, monkeypatch: pytest.MonkeyPatch) -> None:
    def stop(seconds: float) -> None:
        raise KeyboardInterrupt

    monkeypatch.setattr(watch.time, "sleep", stop)
    with pytest.raises(KeyboardInterrupt):
        watch.main(name)


