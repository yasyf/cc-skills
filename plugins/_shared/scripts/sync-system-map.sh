#!/usr/bin/env bash
set -euo pipefail

usage="usage: sync-system-map.sh <cc-present tag> | --check"
arg="${1:?$usage}"
shared="$(cd "$(dirname "$0")/.." && pwd)"
root="$(cd "$shared/../.." && pwd)"
repo="yasyf/cc-present"
src="plugin/.claude/components/display/src/system-map.js"
kit="$shared/html/components.js"
out="$shared/components/dd.system.json"
doc="$root/plugins/design-doc/skills/design-doc/reference/schema.md"

pinned() { sed -n "s#^const SYSMAP_LIB=\"https://cdn\.jsdelivr\.net/gh/$repo@\([^/]*\)/.*#\1#p" "$kit"; }
stated() { grep -o "$repo@[^\`]*" "$doc" | sed "s#^$repo@##" | sort -u; }

derived() {
  curl -fsSL "https://raw.githubusercontent.com/$repo/$1/plugin/.claude/components/display/schema/system.json" \
    | jq --arg repo "$repo" --arg ref "$1" '
      {"$comment": "generated by sync-system-map.sh from \($repo)@\($ref); edit the source there"}
      + (del(.properties.id, .properties.type)
        | .required = ["kind"] + (.required - ["id", "type"])
        | .properties = {kind: {const: "dd.system"}} + .properties)'
}

if [ "$arg" = "--check" ]; then
  ref="$(pinned)"
  status=0
  if [ "$(stated)" != "$ref" ]; then
    echo "sync-system-map: components.js pins $repo@$ref but reference/schema.md states $(stated | paste -sd, -); rerun sync-system-map.sh $ref" >&2
    status=1
  fi
  if ! diff -u <(jq -S . "$out") <(derived "$ref" | jq -S .) >&2; then
    echo "sync-system-map: components/dd.system.json differs from $repo@$ref's schema/system.json; rerun sync-system-map.sh $ref" >&2
    status=1
  fi
  [ "$status" = 1 ] || echo "sync-system-map: dd.system matches $repo@$ref"
  exit "$status"
fi

case "$arg" in -*) echo "$usage" >&2; exit 2 ;; esac
old="$(pinned)"
derived "$arg" >"$out.tmp"
mv "$out.tmp" "$out"
sed -i.bak "s#\(cdn\.jsdelivr\.net/gh/$repo@\)[^/]*/#\1$arg/#" "$kit"
sed -i.bak -e "s#$repo@[^\`]*\`#$repo@$arg\`#g" -e "s#$repo/blob/[^/]*/#$repo/blob/$arg/#g" "$doc"
rm "$kit.bak" "$doc.bak"
python3 "$shared/build.py" build >/dev/null
echo "sync-system-map: pinned $repo@$arg (was $old), wrote components/dd.system.json, rebuilt the templates"
[ "$old" != "$arg" ] || exit 0
echo "commits touching $src from $old to $arg:"
shas="$(gh api "repos/$repo/compare/$old...$arg" --jq '.commits[].sha')"
gh api "repos/$repo/commits?sha=$arg&path=$src&per_page=100" --jq '.[] | "\(.sha) \(.commit.message | split("\n")[0])"' \
  | grep -F -f <(printf '%s\n' "$shas") | sed 's/^\(.\{7\}\)[^ ]* /  \1 /' || echo "  none"
